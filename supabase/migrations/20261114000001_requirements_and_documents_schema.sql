-- Permitayo, Phase 4: requirements and document management (schema).
-- Tables: permit_requirements, application_documents, document_review_history.
-- Security (grants, RLS, storage policies, definer functions) is in the next migration.
--
-- Files live in the EXISTING private Storage bucket 'permit-documents' (Phase 2),
-- under {applicant_id}/{application_id}/{requirement_id}/{generated_file_id}.{ext}.
-- No second bucket is created.

-- File types Permitayo can accept at all. Per-requirement lists must be a subset.
create or replace function public.allowed_document_mime_types()
returns text[]
language sql
immutable
set search_path = ''
as $$
  select array['application/pdf', 'image/jpeg', 'image/png']::text[]
$$;

-- ---------------------------------------------------------------------------
-- permit_requirements: configurable requirements per permit type
-- ---------------------------------------------------------------------------
create table public.permit_requirements (
  id uuid primary key default gen_random_uuid(),
  permit_type_id uuid not null references public.permit_types (id) on delete restrict,
  name text not null
    constraint permit_requirements_name_length check (char_length(btrim(name)) between 2 and 160),
  description text
    constraint permit_requirements_description_length check (description is null or char_length(description) <= 1000),
  applicant_instructions text
    constraint permit_requirements_instructions_length check (applicant_instructions is null or char_length(applicant_instructions) <= 1000),
  is_required boolean not null default true,
  accepted_file_types text[] not null default array['application/pdf', 'image/jpeg', 'image/png']::text[]
    constraint permit_requirements_file_types_valid check (
      cardinality(accepted_file_types) >= 1
      and accepted_file_types <@ public.allowed_document_mime_types()
    ),
  -- Bytes. Default 5 MB; the bucket itself caps every file at 10 MB.
  max_file_size integer not null default 5242880
    constraint permit_requirements_max_size_range check (max_file_size between 102400 and 10485760),
  display_order integer not null default 0
    constraint permit_requirements_display_order_range check (display_order between 0 and 10000),
  is_active boolean not null default true,
  -- Reserved for future conditional requirements (for example, only for certain
  -- ownership types). Not evaluated in Phase 4: every active requirement applies.
  conditions jsonb not null default '{}'::jsonb
    constraint permit_requirements_conditions_object check (jsonb_typeof(conditions) = 'object'),
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index permit_requirements_type_order_idx on public.permit_requirements (permit_type_id, display_order, name);
create index permit_requirements_active_idx on public.permit_requirements (permit_type_id) where is_active;
create unique index permit_requirements_type_name_key on public.permit_requirements (permit_type_id, lower(name));

create trigger permit_requirements_set_updated_at
  before update on public.permit_requirements
  for each row execute function public.set_updated_at();

comment on table public.permit_requirements is
  'Document requirements per permit type, configured by BPLO personnel and administrators. Seeded rows are inactive samples.';

-- ---------------------------------------------------------------------------
-- application_documents: one row per uploaded file (every version is kept)
-- ---------------------------------------------------------------------------
create table public.application_documents (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.permit_applications (id) on delete restrict,
  requirement_id uuid not null references public.permit_requirements (id) on delete restrict,
  applicant_id uuid not null references public.profiles (id) on delete restrict,
  original_filename text not null
    constraint application_documents_filename_length check (char_length(original_filename) between 1 and 255),
  -- Object name inside the 'permit-documents' bucket. Generated by the server.
  storage_path text not null,
  mime_type text not null
    constraint application_documents_mime_allowed check (mime_type = any (public.allowed_document_mime_types())),
  file_size integer not null
    constraint application_documents_size_range check (file_size between 1 and 10485760),
  submission_version integer not null
    constraint application_documents_version_positive check (submission_version >= 1),
  -- Only the newest version of a requirement's document is current.
  is_current boolean not null default true,
  document_status text not null default 'uploaded'
    constraint application_documents_status_allowed check (
      document_status in ('uploaded', 'under_review', 'accepted', 'needs_resubmission')
    ),
  -- Latest review, denormalised for the checklist. Full trail: document_review_history.
  review_comment text
    constraint application_documents_review_comment_length check (review_comment is null or char_length(review_comment) <= 1000),
  last_reviewed_by uuid references public.profiles (id) on delete set null,
  last_reviewed_at timestamptz,
  uploaded_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint application_documents_storage_path_key unique (storage_path),
  constraint application_documents_version_key unique (application_id, requirement_id, submission_version)
);

create unique index application_documents_one_current_idx
  on public.application_documents (application_id, requirement_id) where is_current;
create index application_documents_application_idx on public.application_documents (application_id, requirement_id, submission_version desc);
create index application_documents_applicant_idx on public.application_documents (applicant_id);
create index application_documents_status_idx on public.application_documents (document_status) where is_current;
create index application_documents_requirement_idx on public.application_documents (requirement_id);

create trigger application_documents_set_updated_at
  before update on public.application_documents
  for each row execute function public.set_updated_at();

comment on table public.application_documents is
  'Uploaded supporting documents. Written only by definer functions; replaced versions are kept with is_current = false.';

-- ---------------------------------------------------------------------------
-- document_review_history: append-only manual review trail
-- ---------------------------------------------------------------------------
create table public.document_review_history (
  id uuid primary key default gen_random_uuid(),
  application_document_id uuid not null references public.application_documents (id) on delete restrict,
  reviewed_by uuid references public.profiles (id) on delete set null,
  previous_status text not null,
  new_status text not null
    constraint document_review_history_status_allowed check (new_status in ('under_review', 'accepted', 'needs_resubmission')),
  review_comment text
    constraint document_review_history_comment_length check (review_comment is null or char_length(review_comment) <= 1000),
  created_at timestamptz not null default now()
);

create index document_review_history_document_idx on public.document_review_history (application_document_id, created_at);
