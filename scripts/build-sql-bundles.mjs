// Builds the copy-paste SQL files for the Supabase SQL editor from supabase/migrations.
//   supabase/setup-all.sql      every migration, for a NEW, empty Permitayo project
//   supabase/phase3-upgrade.sql Phase 3 migrations only, for a project that already ran the Phase 2 setup
//   supabase/phase4-upgrade.sql Phase 4 migrations only, for a project that already has Phases 2 and 3
// Run: node scripts/build-sql-bundles.mjs   (the migrations stay the source of truth)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const PHASE3_FROM = "20261111";
const PHASE4_FROM = "20261114";

function bundle(list, header) {
  const parts = list.map((f) => {
    const body = readFileSync(path.join(dir, f), "utf8").replace(/\s+$/, "");
    const bar = "-- " + "=".repeat(68);
    return `${bar}\n-- ${f}\n${bar}\n${body}\n`;
  });
  return `${header}\n\n${parts.join("\n")}`;
}

writeFileSync(
  path.join(root, "supabase", "setup-all.sql"),
  bundle(
    files,
    `-- Permitayo: complete database setup (all ${files.length} migrations in order, Phases 2 to 4).\n` +
      "-- Paste this whole file into Supabase > SQL Editor and click Run. Run it ONCE on an empty Permitayo project.\n" +
      "-- Upgrading an existing project? Run only the phaseN-upgrade.sql files you have not run yet, in order.\n" +
      "-- Generated by scripts/build-sql-bundles.mjs. Do not edit by hand.",
  ),
);

const phase3 = files.filter((f) => f >= PHASE3_FROM && f < PHASE4_FROM);
writeFileSync(
  path.join(root, "supabase", "phase3-upgrade.sql"),
  bundle(
    phase3,
    `-- Permitayo Phase 3 upgrade: business profiles and permit applications (${phase3.length} migrations).\n` +
      "-- For a project that ALREADY ran the Phase 2 setup-all.sql. Paste into Supabase > SQL Editor and click Run, ONCE.\n" +
      "-- It only adds new tables, functions and policies; Phase 2 tables and data are not changed.\n" +
      "-- Then run supabase/verify.sql and check that every result equals expected.\n" +
      "-- Generated by scripts/build-sql-bundles.mjs. Do not edit by hand.",
  ),
);
const phase4 = files.filter((f) => f >= PHASE4_FROM);
writeFileSync(
  path.join(root, "supabase", "phase4-upgrade.sql"),
  bundle(
    phase4,
    `-- Permitayo Phase 4 upgrade: requirements and document management (${phase4.length} migrations).\n` +
      "-- For a project that ALREADY has Phases 2 and 3. Paste into Supabase > SQL Editor and click Run, ONCE.\n" +
      "-- Adds tables, functions and policies, reuses the existing private 'permit-documents' bucket, and replaces\n" +
      "-- the Phase 2 storage upload policy with a stricter one. Existing data is not changed.\n" +
      "-- Then run supabase/verify.sql and check that every result equals expected.\n" +
      "-- Generated by scripts/build-sql-bundles.mjs. Do not edit by hand.",
  ),
);
console.log(`setup-all.sql: ${files.length}; phase3-upgrade.sql: ${phase3.length}; phase4-upgrade.sql: ${phase4.length} migrations`);
